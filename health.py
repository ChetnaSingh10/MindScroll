num_features = df.select_dtypes(include='number')
Q1 = num_features.quantile(0.25)
Q3 = num_features.quantile(0.75)
IQR = Q3 - Q1
lower_bound =  Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR
outliers = (num_features < lower_bound) | (num_features > upper_bound)
print(outliers.sum())

df= df.drop_duplicates()

df['Physical_Activity_Hours']=df['Physical_Activity_Hours'].clip(lower=0)
df['Study_Hours']=df['Study_Hours'].clip(lower=0)

num_cols = df.select_dtypes(include='number')
num_cols.skew()

top_countries=df['Country'].value_counts().index[:10].tolist()

def group_countries(country):
  if country in top_countries:
    return country
  else:
    return 'Other'

df['Grouped_country'] = df['Country'].apply(group_countries)

df['Grouped_country'].value_counts()

skew_col = ['Study_Hours']
numerical_cols = [
    'Age','Avg_Daily_Usage_Hours','Daily_Unlocks','Physical_Activity_Hours','Sleep_Hours_Per_Night'
]
ordinal_cols= ['Stress_Level']
categorical_cols = [
    'Gender','Grouped_country','Academic_Level','Most_Used_Platform','Purpose_Of_Use'
]
feature_col = numerical_cols+ordinal_cols+categorical_cols+skew_col

from sklearn.preprocessing import OneHotEncoder
from sklearn.preprocessing import StandardScaler
from sklearn.preprocessing import OrdinalEncoder
from sklearn.model_selection import train_test_split

from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import FunctionTransformer

X = df[feature_col]
y = df['Mental_Health_Score']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.30, random_state=42)
print("\nTraining Samples:", X_train.shape[0])
print("Testing Samples:", X_test.shape[0])

skew_pipeline = Pipeline([
    (
        'log_transform',
        FunctionTransformer(np.log1p)
     ),
    (
        'scaler',
        StandardScaler()
    )
])

numerical_pipeline = Pipeline([
    (
        "scaler",
        StandardScaler()
    )
])

ordinal_pipeline = Pipeline([
    (
        'encoder',
        OrdinalEncoder(categories=[['Low','Medium','High','Very High']])
    )
])

categorical_pipeline = Pipeline([
    (
        "encoder",
        OneHotEncoder(handle_unknown="ignore")
    )
])

preprocessor = ColumnTransformer([
    (
        "skew",
        skew_pipeline,
        skew_col
    ),
    (
        "numerical",
        numerical_pipeline,
        numerical_cols
    ),
    (
        "categorical",
        categorical_pipeline,
        categorical_cols
    ),
    (
        "ordinal",
        ordinal_pipeline,
        ordinal_cols
    )
])

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error,r2_score,mean_squared_error

lr_pipeline = Pipeline(steps=[
    ('preprocessor',preprocessor),
    ('regressor',LinearRegression())
])

lr_pipeline.fit(X_train,y_train)
lr_pred = lr_pipeline.predict(X_test)
lr_pred_train = lr_pipeline.predict(X_train)

lr_r2_testing = r2_score(y_test,lr_pred)
lr_r2_training = r2_score(y_train,lr_pred_train)
lr_mae= mean_absolute_error(y_test, lr_pred)
print(f"Accuracy of Training : {lr_r2_training}")
print(f"Accuracy of Testing : {lr_r2_testing}")
print(f'MAE : {lr_mae}')

from sklearn.ensemble import RandomForestRegressor

rf_pipeline = Pipeline(steps=[
    ('preprocessor',preprocessor),
    ('random_forest',RandomForestRegressor(random_state=42))
])

rf_pipeline.fit(X_train,y_train)
rf_pred = rf_pipeline.predict(X_test)
rf_pred_train = rf_pipeline.predict(X_train)

rf_r2_testing = r2_score(y_test,rf_pred)
rf_r2_training = r2_score(y_train,rf_pred_train)
rf_mae= mean_absolute_error(y_test, rf_pred)
print(f"Accuracy of Training : {rf_r2_training}")
print(f"Accuracy of Testing : {rf_r2_testing}")
print(f'MAE : {rf_mae}')

from sklearn.model_selection import RandomizedSearchCV

param_grid = {
    "random_forest__n_estimators": [100, 200, 300],
    "random_forest__max_depth": [5, 10, 15],
    "random_forest__min_samples_split": [2, 5, 10],
    "random_forest__min_samples_leaf": [1, 2, 4]
}

random_search = RandomizedSearchCV(
    estimator=rf_pipeline,
    param_distributions=param_grid,
    n_iter=15,
    cv=5,
    scoring="r2",
    random_state=42,
    n_jobs=-1
)

random_search.fit(X_train, y_train)

random_search.best_params_

rf_best_pipeline = random_search.best_estimator_
rf_best_pred    = rf_best_pipeline.predict(X_test)

from sklearn.metrics import mean_squared_error

lr_rmse = np.sqrt(mean_squared_error(y_test, lr_pred))

rf_rmse = np.sqrt(mean_squared_error(y_test, rf_pred))

rf_tuned_pred          = random_search.best_estimator_.predict(X_test)
rf_tuned_rmse           = np.sqrt(mean_squared_error(y_test, rf_tuned_pred))
rf_tuned_training_pred = random_search.best_estimator_.predict(X_train)
r2_tuned_training       = r2_score(y_train, rf_tuned_training_pred)
rf_tuned_mae            = mean_absolute_error(y_test, rf_tuned_pred)
rf_tuned_r2             = r2_score(y_test, rf_tuned_pred)


results = pd.DataFrame({
    'Model': ['Linear Regression', 'Random Forest (default)', 'Random Forest (tuned)'],
    'R2': [lr_r2_testing, rf_r2_testing, rf_tuned_r2],
    'Training R2': [lr_r2_training, rf_r2_training, r2_tuned_training],
    'MAE': [lr_mae, rf_mae, rf_tuned_mae],
    'RMSE': [lr_rmse, rf_rmse, rf_tuned_rmse]
})

print(results)

joblib.dump(rf_best_pipeline, 'Mental_Health_Model.pkl')

